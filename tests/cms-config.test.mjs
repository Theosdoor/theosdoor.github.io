import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { load } from 'js-yaml';
import {
  yamlKeys,
  projectSchema,
  talkSchema,
  pubSchema,
  reviewingSchema,
  fieldBuildingSchema,
  introSchema,
  affiliationTypes,
} from '../src/content-schemas.ts';

const read = (path) => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const config = load(await read('public/admin/config.yml'));
const collection = (name) => {
  const c = config.collections.find((x) => x.name === name);
  assert.ok(c, `collection ${name} missing from config.yml`);
  return c;
};
const fileOf = (name) => collection(name).files[0];

// Unwrap optional/nullable and report what is inside.
function describe(schema) {
  let optional = schema.isOptional();
  let inner = schema;
  while (inner.def.innerType) inner = inner.def.innerType;
  return { optional, inner, type: inner.def.type };
}

// Compare a zod object with a list of CMS fields: names, required-ness, enums, nesting.
function checkFields(schema, fields, where, ignore = []) {
  const expected = Object.keys(schema.shape).filter((k) => !ignore.includes(k));
  const actual = fields.map((f) => f.name).filter((n) => !ignore.includes(n));
  assert.deepEqual(actual.toSorted(), expected.toSorted(), `${where}: field names differ`);
  for (const field of fields) {
    if (ignore.includes(field.name)) continue;
    const { optional, inner, type } = describe(schema.shape[field.name]);
    const w = `${where}.${field.name}`;
    assert.equal(field.required === false, optional, `${w}: required/optional mismatch`);
    if (type === 'enum') {
      assert.equal(field.widget, 'select', `${w}: enum needs a select widget`);
      assert.deepEqual([...field.options].sort(), [...inner.options].sort(), `${w}: enum options differ`);
    } else if (type === 'boolean') {
      assert.equal(field.widget, 'boolean', w);
    } else if (type === 'number') {
      assert.equal(field.widget, 'number', w);
    } else if (type === 'array') {
      assert.equal(field.widget, 'list', w);
      const element = inner.element;
      if (element.def.type === 'object') checkFields(element, field.fields, w);
      else assert.ok(field.field, `${w}: list of strings needs a single \`field\``);
    } else {
      assert.ok(['string', 'text', 'image', 'markdown'].includes(field.widget), `${w}: unexpected widget ${field.widget}`);
    }
  }
}

// A YAML file holding a single list under `key`.
function checkYamlList(name, key, schema) {
  const file = fileOf(name);
  assert.match(file.file, new RegExp(`^content/.+\\.yaml$`));
  assert.equal(file.fields.length, 1, `${name}: expected one top-level list`);
  assert.equal(file.fields[0].name, key, `${name}: list key differs from the loader key`);
  assert.equal(file.fields[0].widget, 'list');
  return file.fields[0];
}

test('projects, talks and publications mirror the content schemas', () => {
  for (const [name, key, schema] of [
    ['projects', yamlKeys.projects, projectSchema],
    ['talks', yamlKeys.talks, talkSchema],
    ['publications', yamlKeys.pubs, pubSchema],
  ]) {
    const list = checkYamlList(name, key, schema);
    checkFields(schema, list.fields, name, ['id']); // `id` is generated by the loader
  }
});

test('reviewing is a list of plain strings under the loader key', () => {
  const list = checkYamlList('reviewing', yamlKeys.reviewing, reviewingSchema);
  assert.deepEqual(Object.keys(reviewingSchema.shape), ['name']);
  assert.equal(list.field.name, 'name');
});

test('field-building folder collection mirrors its schema', () => {
  const c = collection('field_building');
  assert.equal(c.folder, 'content/field-building');
  assert.equal(c.extension, 'md');
  checkFields(fieldBuildingSchema, c.fields.filter((f) => f.name !== 'body'), 'field_building');
  assert.ok(c.fields.some((f) => f.name === 'body' && f.widget === 'markdown'), 'markdown body field missing');
});

test('intro front matter fields mirror introSchema and the real file validates', async () => {
  const file = fileOf('intro');
  assert.equal(file.file, 'content/intro.md');
  checkFields(introSchema, file.fields.filter((f) => f.name !== 'body'), 'intro');
  const affiliationType = file.fields.find((f) => f.name === 'affiliations').fields.find((f) => f.name === 'type');
  assert.deepEqual([...affiliationType.options].sort(), [...affiliationTypes].sort());

  const raw = await read('content/intro.md');
  const front = load(raw.match(/^---\n([\s\S]*?)\n---/)[1]);
  const parsed = introSchema.safeParse(front);
  assert.ok(parsed.success, `content/intro.md front matter invalid: ${parsed.error}`);
});

test('the intro schema fails loudly when a field is missing', () => {
  assert.equal(introSchema.safeParse({ name: 'x', subtitle: 'y' }).success, false);
});

test('the admin page is noindex and pins the CMS version', async () => {
  const html = await read('public/admin/index.html');
  assert.match(html, /<meta name="robots" content="noindex/);
  assert.match(html, /@sveltia\/cms@\d+\.\d+\.\d+\/dist\/sveltia-cms\.js/);
  assert.doesNotMatch(html, /sveltia\/cms(@latest)?\/dist/);
});

test('config.yml carries no secrets', async () => {
  const text = await read('public/admin/config.yml');
  assert.doesNotMatch(text, /ghp_|github_pat_|token\s*:/i);
});

test('every image folder maps /images/... site paths onto src/assets/images', () => {
  for (const c of [config, collection('projects'), collection('publications')]) {
    assert.ok(c.media_folder.startsWith('src/assets/images'));
    assert.ok(c.public_folder.startsWith('/images'));
    assert.equal(c.media_folder.replace('src/assets', ''), c.public_folder);
  }
});
